"""Export the original athlete (body LOD0 + hair + skeleton + every action as its own take) as an FBX for Unreal.
  Blender -b Assets/Characters/out/player.blend --python Tools/blender/export_fbx_for_unreal.py -- out.fbx
Original asset (generated by make_football_player.py) -> no third-party licence involved."""
import bpy, sys
out = sys.argv[sys.argv.index('--') + 1]
for o in bpy.data.objects: o.select_set(False)
# Join hair into the body so Unreal gets ONE skeletal mesh with all 6 material slots (separate meshes overwrote each other on import).
for o in bpy.data.objects:
    o.hide_set(False); o.hide_viewport = False; o.hide_select = False
bpy.ops.object.select_all(action='DESELECT')
body, hair = bpy.data.objects['body'], bpy.data.objects['hair']
for o in (body, hair):
    if not any(m.type == 'ARMATURE' for m in o.modifiers):
        mod = o.modifiers.new('Armature', 'ARMATURE'); mod.object = bpy.data.objects['skeleton']
    o.select_set(True)
bpy.context.view_layer.objects.active = body
bpy.ops.object.join()
body.name = 'athlete_mesh'
print('JOINED verts', len(body.data.vertices), 'materials', [m.name for m in body.data.materials], 'groups', len(body.vertex_groups))
for o in bpy.data.objects: o.select_set(False)
body.select_set(True); bpy.data.objects['skeleton'].select_set(True)
bpy.context.view_layer.objects.active = bpy.data.objects['skeleton']
# Make the data centimetre-native (scale x100 and apply, scale location keys, scene units = cm) so Unreal's importer adds no x100 root-bone scale
# (that scale made the retargeter collapse every bone onto the hips).
S = 100.0
arm = bpy.data.objects['skeleton']
# Order matters: applying the ARMATURE's scale makes Blender set each child's scale to 100 (to keep its world position), so apply the armature first,
# then apply the child mesh (its verts become x100 and its scale returns to 1). The other order scales the mesh twice.
def apply_scale(obj):
    bpy.ops.object.select_all(action='DESELECT'); obj.select_set(True); bpy.context.view_layer.objects.active = obj
    obj.scale = (S, S, S); bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
mats = {o.name: o.matrix_parent_inverse.copy() for o in (body,)}
def apply_arm(obj):
    bpy.ops.object.select_all(action='DESELECT'); obj.select_set(True); bpy.context.view_layer.objects.active = obj
    obj.scale = (S, S, S); bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
apply_arm(arm)
bpy.ops.object.select_all(action='DESELECT'); body.select_set(True); bpy.context.view_layer.objects.active = body
bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)   # body.scale is already 100 from the parent apply
body.matrix_parent_inverse = mats[body.name]
print('AFTER SCALE: body height', round(body.dimensions.z, 1), 'hips z', round(arm.data.bones['hips'].head_local.z, 1))
def action_fcurves(act):   # Blender 5 layered actions (layers -> strips -> channelbags), with a fallback for the legacy API
    if hasattr(act, 'fcurves'): yield from act.fcurves; return
    for layer in act.layers:
        for strip in layer.strips:
            for bag in getattr(strip, 'channelbags', []): yield from bag.fcurves
scaled = 0
for act in bpy.data.actions:
    for fc in action_fcurves(act):
        if fc.data_path.endswith('location'):
            for kp in fc.keyframe_points: kp.co.y *= S; kp.handle_left.y *= S; kp.handle_right.y *= S
            fc.update(); scaled += 1
print('SCALED location curves:', scaled)
bpy.context.scene.unit_settings.system = 'METRIC'; bpy.context.scene.unit_settings.scale_length = 0.01; bpy.context.scene.unit_settings.length_unit = 'CENTIMETERS'
for o in bpy.data.objects: o.select_set(False)
body.select_set(True); arm.select_set(True); bpy.context.view_layer.objects.active = arm
# Make sure the armature modifier exists on the exported meshes and every action is bakeable.
arm = bpy.data.objects['skeleton']
bpy.ops.export_scene.fbx(filepath=out, use_selection=True, object_types={'ARMATURE', 'MESH'}, add_leaf_bones=False,
    apply_scale_options='FBX_SCALE_NONE', global_scale=1.0, axis_forward='-Y', axis_up='Z', bake_space_transform=False,
    use_mesh_modifiers=True, mesh_smooth_type='FACE', use_armature_deform_only=False, armature_nodetype='NULL',
    bake_anim=True, bake_anim_use_all_actions=True, bake_anim_use_nla_strips=False, bake_anim_force_startend_keying=True,
    bake_anim_step=1.0, bake_anim_simplify_factor=0.0, path_mode='COPY', embed_textures=False)
print('EXPORTED', out, [a.name for a in bpy.data.actions])
